class Resp:
    def __init__(self, body, start, length, total, etag=ETAG):
        self.status, self._b = 206, body
        self.headers = {"Content-Range": f"bytes {start}-{start + length - 1}/{total}", "Content-Length": str(length), "ETag": etag}

    def read(self, n=-1):
        out, self._b = (self._b, b"") if n < 0 else (self._b[:n], self._b[n:])
        return out

    def close(self):
        pass

    def __enter__(self):
        return self

    def __exit__(self, *a):
        return False


def fake_archive(b3d, member=MEMBER, offset=1000, claimed_crc=None):
    comp = zlib.compressobj(wbits=-15)
    payload = comp.compress(b3d) + comp.flush()
    name = member.encode()
    crc = zlib.crc32(b3d) if claimed_crc is None else claimed_crc
    lh = struct.pack("<4s5H3L2H", b"PK\x03\x04", 20, 0, 8, 0, 0, crc, len(payload), len(b3d), len(name), 0) + name
    blob = bytearray(offset) + lh + payload
    calls = []

    def opener(start, length):
        calls.append((start, length))
        return Resp(bytes(blob[start:start + length]), start, length, acq.ARCHIVE["bytes"])
    entry = {"flags": 0, "method": 8, "crc32": crc, "compressed_bytes": len(payload),
             "expanded_bytes": len(b3d), "local_header_offset": offset}
    return opener, entry, calls


def expected_file(tmp, entry, member=MEMBER, header_sha=None):
    p = tmp / "expected.json"
    p.write_text(json.dumps({"member": member, **entry, "archive": acq.ARCHIVE, "drive_header_sha256": header_sha}))
    return p


def run(tmp, opener, exp, out="dest/fa16/subject_0", receipts="receipts/fa16_subject_0", **kw):
    d = json.loads(Path(exp).read_text())
    kw.setdefault("central", lambda: {d["member"]: {k: d[k] for k in acq.CD_KEYS}})
    kw.setdefault("fixed_root", tmp / "dest")
    kw.setdefault("free_bytes", lambda p: 10 ** 15)
    kw.setdefault("free_mib", lambda: 8000)
    kw.setdefault("rate", 10 ** 12)
    return acq.run(exp, tmp / out, tmp / receipts, tmp / "dest", opener=opener,
                   sleep=lambda s: None, **kw)


