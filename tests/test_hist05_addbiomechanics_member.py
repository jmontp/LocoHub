# Reader stub with values from the fixture's own encoding rule (independent of the converter):
# pass code c, trial t, frame f -> base = 1000c + 100t + f.
class _P:
    def __init__(self, code, trial, frame, bump=0.0):
        base = 1000 * code + 100 * trial + frame
        self.type = type("T", (), {"name": {0: "KINEMATICS", 1: "DYNAMICS", 2: "LOW_PASS_FILTER"}[code]})()
        self.pos = [base + 0.1 * i for i in range(NDOF)]
        self.vel, self.acc = [base + 0.2] * NDOF, [base + 0.3] * NDOF
        self.tau = [base + 0.4 + i + bump for i in range(NDOF)]
        self.groundContactCenterOfPressure, self.groundContactTorque = [base + 0.6] * 6, [base + 0.7] * 6
        self.groundContactForce = [base + 0.8 + i for i in range(6)]
        self.comPos, self.comVel, self.comAcc = [base + 0.9] * 3, [1.0] * 3, [2.0] * 3
        self.residualWrenchInRootFrame = [3.0] * 6


class _Subject:
    def __init__(self, trials, bump=0.0):
        self.trials, self.bump = trials, bump

    def readFrames(self, trial, start, n, includeSensorData=True, includeProcessingPasses=True):
        order = self.trials[trial][4]
        return [type("F", (), {"processingPasses": [_P(PASS_CODE[p], trial, f, self.bump if (trial, f) == (1, 2) else 0.0)
                                                    for p in order]})() for f in range(start, start + n)]


