# ------------------------------------------------------------- encoder ----

def _v(n):
    out = b""
    while True:
        b = n & 0x7F
        n >>= 7
        if n:
            out += bytes([b | 0x80])
        else:
            return out + bytes([b])


def _key(f, w):
    return _v((f << 3) | w)


def vint(f, n):
    return _key(f, 0) + _v(n)


def ld(f, b):
    return _key(f, 2) + _v(len(b)) + b


def dbl(f, x):
    return _key(f, 1) + struct.pack("<d", x)


def pdbl(f, xs):
    return ld(f, struct.pack(f"<{len(xs)}d", *xs))


def pflt(f, xs):
    return ld(f, struct.pack(f"<{len(xs)}f", *xs))


def pvar(f, xs):
    return ld(f, b"".join(_v(x) for x in xs))


PASS_CODE = {"kinematics": 0, "dynamics": 1, "lowPassFilter": 2}
NDOF, BODIES = 3, ["calcn_r", "calcn_l"]


def model(mass_each):
    bodies = "".join(f'<Body name="b{i}"><mass>{mass_each}</mass></Body>' for i in range(2))
    return (f'<OpenSimDocument><Model name="m">{bodies}<Coordinate name="q0"/><Coordinate name="q1"/>'
            f'<Coordinate name="q2"/></Model></OpenSimDocument>').encode()


def pass_frame(code, trial, frame):
    """Values encode (pass, trial, frame) so the chosen pass is identifiable."""
    base = 1000 * code + 100 * trial + frame
    return (pdbl(1, [base + 0.1 * i for i in range(NDOF)]) + pdbl(2, [base + 0.2] * NDOF) +
            pdbl(3, [base + 0.3] * NDOF) + pdbl(4, [base + 0.4 + i for i in range(NDOF)]) +
            pdbl(6, [base + 0.6] * 6) + pdbl(7, [base + 0.7] * 6) + pdbl(8, [base + 0.8 + i for i in range(6)]) +
            pdbl(9, [base + 0.9] * 3) + pdbl(10, [1.0] * 3) + pdbl(11, [2.0] * 3) + pdbl(12, [3.0] * 6))


def fake_b3d(trials, *, mass=65.5, age=29, sex="male", height=1.76, with_age=True,
             global_order=("kinematics", "lowPassFilter", "dynamics")):
    """trials: list of (name, original, split, timestep, pass_order, length, missing_codes)."""
    sensor = pdbl(2, [0.5] * 6)
    pass_sizes = {len(pass_frame(PASS_CODE[p], t, f)) for t, tr in enumerate(trials) for p in tr[4] for f in range(tr[5])}
    assert len(pass_sizes) == 1
    psize = pass_sizes.pop()
    hdr = vint(1, NDOF) + vint(3, len(sensor)) + vint(4, psize)
    for p in global_order:
        hdr += ld(5, (vint(1, PASS_CODE[p]) if PASS_CODE[p] else b"") + ld(2, model(40.0 if p == "dynamics" else 30.0)))
    hdr += b"".join(ld(6, b.encode()) for b in BODIES)
    for name, original, split, step, order, length, missing in trials:
        th = ld(1, name.encode()) + pvar(2, missing) + vint(3, length) + dbl(4, step) + vint(7, 2) + ld(10, original.encode())
        if split:
            th += vint(11, split)
        for p in order:
            th += ld(5, (vint(1, PASS_CODE[p]) if PASS_CODE[p] else b"") + pflt(5, [0.01] * length) +
                     pflt(7, [0.5] * length) + pflt(8, [0.25] * length))
        hdr += ld(9, th)
    hdr += vint(10, 4) + ld(11, b"https://example.invalid/x") + ld(12, b"Generated by AddBiomechanics")
    hdr += ld(13, sex.encode()) + dbl(14, height) + dbl(15, mass) + (vint(16, age) if with_age else b"")
    hdr += ld(17, b"M1") + ld(23, b"healthy")
    data = struct.pack("<q", len(hdr)) + hdr
    for t, (_, _, _, _, order, length, _) in enumerate(trials):
        for f in range(length):
            data += sensor + b"".join(pass_frame(PASS_CODE[p], t, f) for p in order)
    return data, hashlib.sha256(hdr).hexdigest()


