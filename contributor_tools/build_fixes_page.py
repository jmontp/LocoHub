def figure_gt24_divisor(plt):
    """Per folder: each mass used for per-kg moments relative to the folder's own README mass with exoskeleton."""
    census = load('gt24-c01-e1-census-result.json')
    policy = load('gt24-c01-normalization-policy.json')
    units = {f"{u['phase']}/{u['subject_folder']}": u for u in policy['mass_units']}
    divisors = census['summary']['units_divisors']
    if set(units) != set(divisors):
        raise ValueError('census and policy folders differ')
    other_row = {}
    for key in census['summary']['flagged_other_candidates_by_folder']:
        folder, target = key.split(' -> README ')
        if folder in census['summary']['without_own_readme_match_by_folder'] or any(
                folder in k for k in census['summary']['without_own_readme_match_by_folder']):
            other_row.setdefault(folder, set()).add(target.split()[1])
    names = sorted(units, key=lambda k: (k.split('/')[0] != 'Phase1And2', k.split('/')[1]))
    fig, ax = plt.subplots(figsize=(WIDTH_IN, 6.8), layout='constrained')
    ys = np.arange(len(names))[::-1]
    ax.axvline(0, color=INK, lw=0.9, zorder=1)
    mismatched, swap_devs = [], []
    for y, name in zip(ys, names):
        row = units[name]['readme_row']
        worn = {k.split('_')[1]: float(v) for k, v in row.items() if k.startswith('model_')}        # day -> kg
        body = {k.split('_')[1]: float(v) for k, v in row.items() if k.startswith('participant_')}
        entries = sorted(divisors[name].items(), key=lambda kv: float(kv[0]))
        offsets = [0.0] if len(entries) == 1 else np.linspace(0.22, -0.22, len(entries))
        for (mass, entry), off in zip(entries, offsets):
            d = float(mass)
            day = min(worn, key=lambda k: abs(worn[k] - d))   # nearest own-row worn mass
            dev = 100 * (d / worn[day] - 1)
            own = bool(entry['own_readme_fields'])
            if own and abs(dev) > 0.05:
                raise ValueError(f'{name}: own-row match is not at zero')
            if day in body:
                bdev = 100 * (body[day] / worn[day] - 1)
                ax.plot([bdev, dev], [y + off] * 2, color=GREY, lw=0.8, zorder=0)
                ax.plot(bdev, y + off, 'o', mfc='white', mec=MUTED, mew=1.4, ms=6, zorder=2)
            ax.plot(dev, y + off, 's', color=INK if own else BEFORE, ms=5 if own else 6, zorder=3)
            if not own:
                mismatched.append((name, entry['trials']))
                swap_devs.append(abs(dev))
        if name in other_row:   # label to the right of the zero line and of every marker in the row
            right = max(0.0, max(100 * (float(m) / min(worn.values(), key=lambda w: abs(w - float(m))) - 1) for m in divisors[name]))
            ax.annotate(f'= {"/".join(sorted(other_row[name]))}’s mass', (right, y),
                        xytext=(8, 0), textcoords='offset points', ha='left', va='center', fontsize=10, color=INK)
    labels = [f"{n.split('/')[1]} ({'1–2' if n.startswith('Phase1And2') else '3'})" for n in names]
    ax.set_yticks(ys)
    ax.set_yticklabels(labels)
    ax.set_xlabel('Mass used vs. the person’s body mass\nplus exoskeleton, from the README (%)')
    ax.set_ylabel('Participant (study part 1–2 or 3)')
    ax.set_xlim(-16, 38)
    ax.set_ylim(-0.7, len(names) + 1.2)
    ax.text(0, len(names) - 0.3, '0 = body mass plus\nexoskeleton (correct)', ha='left', va='bottom', fontsize=10, color=INK)
    ax.grid(axis='x', color=GREY, lw=0.4, alpha=0.6)
    handles = [
        plt.Line2D([], [], ls='', marker='s', color=INK, ms=5, label='Mass used: the person’s own, with exoskeleton'),
        plt.Line2D([], [], ls='', marker='s', color=BEFORE, ms=6, label='Mass used: another participant’s'),
        plt.Line2D([], [], ls='', marker='o', mfc='white', mec=MUTED, mew=1.4, ms=6, label='The person’s body mass alone, for comparison')]
    fig.legend(handles=handles, loc='outside lower left', handletextpad=0.4)
    summary = census['summary']
    if summary['own_body_mass_matches'] or sum(summary['by_group'].values()) != summary['trials']:
        raise ValueError('census no longer reports every recording divided by a worn mass')
    swapped = sum(summary['without_own_readme_match_by_folder'].values())
    if swapped != sum(t for _, t in mismatched):
        raise ValueError('swap count disagrees between census summary and per-folder divisors')
    spread = policy['readme_mass_spread']['worn_minus_body_kg']
    ratio = policy['readme_mass_spread']['worn_over_body']
    figure_gt24_divisor.lower_pct = (100 * (1 - 1 / ratio[0]), 100 * (1 - 1 / ratio[1]))
    figure_gt24_divisor.swap_range = (min(swap_devs), max(swap_devs))
    return fig, summary['trials'], len(names), sorted({m.split('/')[1] for m, _ in mismatched}), swapped, spread


MONTHS = ('January', 'February', 'March', 'April', 'May', 'June', 'July', 'August', 'September', 'October',
          'November', 'December')


def decision_answer(backlog, decision_id):
    """The recorded answer of an answered decision, or None."""
    for d in backlog.get('decisions', []):
        if d['id'] == decision_id and d.get('status') == 'answered':
            day = d.get('answered_at_utc', '')[:10]
            when = f'{int(day[8:10])} {MONTHS[int(day[5:7]) - 1]} {day[:4]}' if len(day) == 10 else day
            return d.get('answer'), d.get('answer_text', ''), when
    return None


