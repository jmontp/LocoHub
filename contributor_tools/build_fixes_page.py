def plain_condition(code):
    """UM21 condition codes in words: i5 -> 5° incline, d10 -> 10° decline, i0 -> level."""
    if code == 'i0':
        return 'level'
    return f'{code[1:]}° {"incline" if code[0] == "i" else "decline"}'


