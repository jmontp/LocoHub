def spliced_compare(section):
    """The comparison page with only its marked original-vs-fixed section replaced."""
    text = COMPARE.read_text(encoding='utf-8')
    start, end = ORIGINAL_VS_FIXED
    if text.count(start) != 1 or text.count(end) != 1 or text.index(start) > text.index(end):
        raise SystemExit(f'{COMPARE.relative_to(ROOT)} needs exactly one pair of original-vs-fixed markers')
    head, rest = text.split(start)
    _, tail = rest.split(end)
    return f'{head}{start}\n{section}\n{end}{tail}'


def main():
    parser = argparse.ArgumentParser(description=__doc__.split('\n')[0])
    parser.add_argument('--check', action='store_true', help='Fail if the page or a figure differs from a fresh build.')
    args = parser.parse_args()
    produced = {}
    cards, context, outline, skipped, compare = build(lambda name, data: produced.__setitem__(FIG_DIR / f'{name}.svg', data))
    produced[PAGE] = page_html(cards, context, outline).encode('utf-8')
    produced[COMPARE] = spliced_compare(compare_section_html(compare, outline)).encode('utf-8')
    for task in skipped:
        print(f'skipped {task}: task not done or verification not done', file=sys.stderr)
    if args.check:
        stale = [p for p, data in produced.items() if not p.is_file() or p.read_bytes() != data]
        if stale:
            raise SystemExit('Stale: ' + ', '.join(str(p.relative_to(ROOT)) for p in stale))
        print(f'Current: {len(cards)} cards, {len(produced) - 2} figures, comparison section.')
        return
    FIG_DIR.mkdir(parents=True, exist_ok=True)
    for path, data in produced.items():
        path.write_bytes(data)
    print(f'Wrote {PAGE.relative_to(ROOT)} with {len(cards)} cards and {len(produced) - 2} figures; '
          f'updated the original-vs-fixed section of {COMPARE.relative_to(ROOT)}.')


if __name__ == '__main__':
    main()
