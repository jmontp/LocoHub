def figure_gt23_mass(plt):
    """One marker per participant: how far the mass used is from the person's own mass, in %."""
    subjects = load('gt23-c03-normalizing-mass.json')['subjects']
    names = sorted(subjects)
    fig, ax = plt.subplots(figsize=(WIDTH_IN, 4.4), layout='constrained')
    ys = np.arange(len(names))[::-1]
    ax.axvline(0, color=INK, lw=0.9, zorder=1)
    devs = {}
    for y, name in zip(ys, names):
        row = subjects[name]
        dev = 100 * (row['divisor_kg_best'] / row['readme_mass_kg'] - 1)
        devs[name] = dev
        wrong = not row['readme_consistent']
        exact = row['divisor_basis'].startswith('local N*m re-run')
        ax.plot([0, dev], [y, y], color=GREY, lw=1.0, zorder=0)
        ax.plot(dev, y, 's' if exact else '^', color=BEFORE if wrong else MUTED, ms=7, zorder=3)
        others = [o for o in names if o != name and abs(subjects[o]['readme_mass_kg'] - row['divisor_kg_best']) <= 0.05]
        if wrong and exact and len(others) == 1:
            ax.annotate(f'{others[0]}’s mass', (dev, y), xytext=(7 if dev > 0 else -7, 0), textcoords='offset points',
                        ha='left' if dev > 0 else 'right', va='center', fontsize=10, color=INK)
    ax.set_yticks(ys)
    ax.set_yticklabels(names)
    ax.set_xlabel('Mass used vs. the person’s own body mass (%)')
    ax.set_xlim(-62, 48)
    ax.set_ylim(-0.7, len(names) + 0.4)
    ax.text(0, len(names) - 0.25, '0 = the person’s own mass (correct)', ha='center', va='bottom', fontsize=10, color=INK)
    ax.grid(axis='x', color=GREY, lw=0.4, alpha=0.6)
    handles = [
        plt.Line2D([], [], ls='', marker='s', color=BEFORE, ms=7, label='Other mass used; worked out exactly'),
        plt.Line2D([], [], ls='', marker='^', color=BEFORE, ms=7, label='Other mass used; estimated from force plates'),
        plt.Line2D([], [], ls='', marker='s', color=MUTED, ms=7, label='Person’s own mass used (either method)')]
    fig.legend(handles=handles, loc='outside lower left', handletextpad=0.4)
    wrong = [n for n in names if not subjects[n]['readme_consistent']]
    factors = [subjects[n]['scale_factor_published_vs_readme_normalized'] for n in wrong]
    return fig, len(wrong), len(names), min(factors), max(factors), min(devs[n] for n in wrong), max(devs[n] for n in wrong)


